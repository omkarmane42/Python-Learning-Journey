
# STRING PROGRAMS

text = "Python Programming"

print(text)

# Length
print(len(text))

# Uppercase
print(text.upper())

# Lowercase
print(text.lower())

# Replace
print(text.replace("Python", "Java"))

# Split
print(text.split())

# String slicing
print(text[0:6])

# Reverse string
print(text[::-1])

# Check substring
print("Python" in text)