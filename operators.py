
# Operators in Python

a = 10
b = 3

# Arithmetic Operators
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)

# Comparison Operators
print(a > b)
print(a < b)
print(a == b)
print(a != b)

# Logical Operators
x = True
y = False

print(x and y)
print(x or y)
print(not x)

# Assignment Operators
num = 5
num += 3
print(num)

# Identity Operators
print(a is b)
print(a is not b)

# Membership Operators
name = "Python"
print("P" in name)
print("z" not in name)